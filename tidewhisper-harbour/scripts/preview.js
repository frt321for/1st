for (let z = 30; z >= -30; z -= 2) {
  let row = (z >= 0 ? ' ' : '') + z + '  ';
  for (let x = -30; x <= 30; x += 2) {
    let ch = levelChar(T.groundH(x, z));
    for (const k in POI) {
      const [px, pz] = POI[k];
      if (Math.abs(x - px) < 1.1 && Math.abs(z - pz) < 1.1) { ch = k.length > 1 ? k[0] : k; break; }
    }
    row += ch;
  }
  console.log(row);
}
