function levelChar(h) {
  if (h < -0.2) return '~';
  if (h < 0.9) return '.';
  if (h < 1.7) return '0';
  if (h < 3.4) return '1';
  if (h < 5.1) return '2';
  if (h < 6.8) return '3';
  if (h < 8.5) return '4';
  return '5';
}

